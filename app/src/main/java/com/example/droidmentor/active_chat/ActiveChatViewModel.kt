package com.example.droidmentor.active_chat

import android.util.Log
import androidx.lifecycle.ViewModel
import androidx.lifecycle.viewModelScope
import com.example.droidmentor.BuildConfig
import com.example.droidmentor.buildLLogTag
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.update
import kotlinx.coroutines.launch


/**
 * Identifies the sender role of a message in a conversation turn.
 */
enum class Role {
    USER,       // Indicates a message sent by the human user.
    MODEL       // Indicates a message generated by the AI mentor model.
}

/**
 * Domain model representing a single message item displayed in the chat UI.
 *
 * @property text The body text of the message.
 * @property sender The author ([Role]) who sent the message.
 */
data class ChatMessage(
    val text: String,
    val sender: Role
)


/**
 * ViewModel responsible for managing the state and business logic of the active chat screen.
 * Maintains conversation history in memory, updates UI state flows, and coordinates
 * asynchronous request processing with [GeminiApiService].
 */
class ActiveChatViewModel: ViewModel() {

    private val logTag = buildLLogTag(this::class.java.simpleName)
    private val apiService = GeminiApiService(apiKey = BuildConfig.GEMINI_API_KEY)

    init {
        Log.v(logTag, "init on ${hashCode()}")
    }

    /**
     * Observable stream containing the current list of chat messages in the conversation thread.
     */
    val messages = MutableStateFlow<List<ChatMessage>>(emptyList())

    /**
     * Observable flag indicating whether a network request to the Gemini API is currently in progress.
     */
    val isLoading = MutableStateFlow(false)

    /**
     * Sends a new user message to the chat.
     * Appends the user's message to local state, converts the chat history into API-compatible [Content]
     * objects, and asynchronously requests a response from the mentor via [GeminiApiService].
     *
     * @param userText The raw text string entered by the user.
     */
    fun sendMessage(userText: String) {
        val userMsg = ChatMessage(text = userText, Role.USER)
        messages.update { current -> current + userMsg }

        // Maps domain messages to API request history objects
        val conversationHistory = messages.value.map { msg ->
            Content(
                role = msg.sender.name.lowercase(),
                parts = listOf(Part(text = msg.text))
            )
        }

        // Asynchronous request to the Gemini API
        viewModelScope.launch {
            isLoading.value = true
            val result = apiService.generateContent(conversationHistory)
            isLoading.value = false

            result.onSuccess { mentorReply ->
                messages.update { current ->
                    current + ChatMessage(text = mentorReply, Role.MODEL)
                }
            }.onFailure { error ->
                messages.update { current ->
                    current + ChatMessage(
                        text = "An error happened while trying to communicate with mentor: ${error.message}",
                        Role.MODEL
                    )
                }
            }
        }
    }
}